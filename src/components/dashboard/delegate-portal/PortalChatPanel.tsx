"use client";

import { useEffect, useMemo, useRef, useState } from "react";
import Link from "next/link";
import { MessagesSquare, Send, Loader2, Users, Globe2, UserRound } from "lucide-react";
import { Input } from "@/components/ui/input";
import { Button } from "@/components/ui/button";
import { CountryFlag } from "@/components/ui/CountryFlag";
import { getCountryName } from "@/lib/data/countries";
import { roleLabel } from "@/lib/services/staffService";
import { useAuth } from "@/contexts/AuthContext";
import {
  getUserConversations,
  getConversationMessagesRealtime,
  sendMessage,
  markConversationRead,
  createGroupConversation,
  ConversationData,
  MessageData,
} from "@/lib/services/messageService";
import type { PortalMember } from "./usePortalMembers";

// Top half of the portal right rail: a live committee group-chat stream with a compact
// composer. Finds the committee's group conversation among the user's conversations
// (rules-safe, no extra index) and subscribes to it in real time. If the group doesn't
// exist yet, the first message lazily creates it from the committee roster.
export function PortalChatPanel({
  eventId,
  committeeId,
  committeeMembers,
}: {
  eventId?: string;
  committeeId?: string;
  committeeMembers: PortalMember[];
}) {
  const { user, profile } = useAuth();
  const userName = profile?.displayName || user?.displayName || "Me";
  const userPhoto = profile?.photoURL || user?.photoURL || "";

  // undefined = still resolving conversations; null = none exists yet.
  const [conv, setConv] = useState<ConversationData | null | undefined>(undefined);
  const [messages, setMessages] = useState<MessageData[]>([]);
  const [input, setInput] = useState("");
  const [sending, setSending] = useState(false);
  // Message id whose sender identity (name + profile link) is currently revealed.
  const [revealed, setRevealed] = useState<string | null>(null);
  const scrollRef = useRef<HTMLDivElement>(null);

  // Sender lookup so chat bubbles can show a delegate's assigned country flag
  // instead of their personal avatar/name.
  const memberByUid = useMemo(() => {
    const m = new Map<string, PortalMember>();
    for (const mem of committeeMembers) m.set(mem.uid, mem);
    return m;
  }, [committeeMembers]);

  const hasCommittee = !!committeeId;

  // Find the committee group among the user's conversations (real-time).
  useEffect(() => {
    if (!user || !eventId || !committeeId) {
      setConv(committeeId ? undefined : null);
      return;
    }
    const unsub = getUserConversations(user.uid, (convs) => {
      const match = convs.find(
        (c) => c.type === "group" && c.eventId === eventId && c.committeeId === committeeId
      );
      setConv(match || null);
    });
    return unsub;
  }, [user?.uid, eventId, committeeId]);

  // Stream the conversation's messages.
  useEffect(() => {
    if (!conv?.id || !user) {
      setMessages([]);
      return;
    }
    const unsub = getConversationMessagesRealtime(conv.id, 40, setMessages);
    markConversationRead(conv.id, user.uid).catch(() => {});
    return unsub;
  }, [conv?.id, user?.uid]);

  // Keep pinned to the newest message.
  useEffect(() => {
    const el = scrollRef.current;
    if (el) el.scrollTop = el.scrollHeight;
  }, [messages.length, conv?.id]);

  async function handleSend() {
    const text = input.trim();
    if (!text || sending || !user || !committeeId) return;
    setSending(true);
    setInput("");
    try {
      let cid = conv?.id;
      if (!cid) {
        const uids: string[] = [];
        const names: Record<string, string> = {};
        const photos: Record<string, string> = {};
        for (const m of committeeMembers) {
          uids.push(m.uid);
          names[m.uid] = m.name;
          photos[m.uid] = m.photoURL || "";
        }
        names[user.uid] = userName;
        photos[user.uid] = userPhoto;
        cid = await createGroupConversation(
          user.uid,
          `${committeeId} — Committee`,
          uids,
          names,
          photos,
          { eventId, committeeId, autoGenerated: true }
        );
        // Optimistically adopt the new conversation so the stream subscribes immediately.
        setConv({ id: cid, type: "group", eventId, committeeId } as ConversationData);
      }
      await sendMessage(cid, user.uid, userName, text, {
        type: "group",
        groupName: `${committeeId} — Committee`,
        eventId,
        committeeId,
      });
    } catch (err) {
      console.error("Portal chat send failed:", err);
      setInput(text);
    } finally {
      setSending(false);
    }
  }

  return (
    <div className="glass-card rounded-2xl border border-border/50 flex flex-col overflow-hidden flex-1 min-h-0">
      {/* Header */}
      <div className="px-4 py-3 border-b border-border/40 shrink-0">
        <div className="flex items-center gap-2">
          <MessagesSquare className="w-4 h-4 text-primary" />
          <span className="font-semibold text-sm">Committee Chat</span>
        </div>
        {hasCommittee && (
          <p className="text-[11px] text-muted-foreground truncate mt-0.5">{committeeId}</p>
        )}
      </div>

      {/* Stream */}
      <div ref={scrollRef} className="flex-1 min-h-0 overflow-y-auto px-3 py-3 space-y-2.5">
        {!hasCommittee ? (
          <div className="h-full flex flex-col items-center justify-center text-center gap-2 px-4 text-muted-foreground">
            <Users className="w-8 h-8 text-muted-foreground/30" />
            <p className="text-xs">Your committee chat appears here once you're seated in a committee.</p>
          </div>
        ) : conv === undefined ? (
          <div className="space-y-2.5">
            {[...Array(4)].map((_, i) => (
              <div key={i} className={`flex ${i % 2 ? "justify-end" : "justify-start"}`}>
                <div className="h-8 w-2/3 bg-secondary rounded-2xl animate-pulse" />
              </div>
            ))}
          </div>
        ) : messages.length === 0 ? (
          <div className="h-full flex flex-col items-center justify-center text-center gap-2 px-4 text-muted-foreground">
            <MessagesSquare className="w-8 h-8 text-muted-foreground/30" />
            <p className="text-xs">No messages yet. Say hello to your committee 👋</p>
          </div>
        ) : (
          messages.map((m) => {
            if (m.systemMessage) {
              return (
                <div key={m.id} className="text-center">
                  <span className="text-[10px] text-muted-foreground bg-background px-2 py-0.5 rounded-full border border-border/30">
                    {m.text}
                  </span>
                </div>
              );
            }
            const isMe = m.senderId === user?.uid;
            const mem = memberByUid.get(m.senderId);
            const hasCountry = !!mem?.country;
            const senderName = mem?.name || m.senderName || "Delegate";
            const identityLabel = hasCountry
              ? getCountryName(mem!.country)
              : mem?.role
                ? roleLabel(mem.role)
                : "Observer";
            const isRevealed = revealed === m.id;
            return (
              <div key={m.id} className={`flex ${isMe ? "justify-end" : "justify-start"}`}>
                <div className={`flex max-w-[82%] ${isMe ? "flex-row-reverse" : "flex-row"} items-end gap-1.5`}>
                  {!isMe && (
                    <button
                      type="button"
                      onClick={() => setRevealed((r) => (r === m.id ? null : m.id))}
                      title={hasCountry ? identityLabel : "Show sender"}
                      className="shrink-0 h-6 w-6 flex items-center justify-center rounded-sm hover:opacity-80 transition-opacity"
                    >
                      {hasCountry ? (
                        <CountryFlag code={mem!.country} size={18} />
                      ) : (
                        <Globe2 className="w-4 h-4 text-muted-foreground" />
                      )}
                      <span className="sr-only">Show sender</span>
                    </button>
                  )}
                  <div className={`flex flex-col ${isMe ? "items-end" : "items-start"} min-w-0`}>
                    {!isMe && isRevealed && (
                      <span className="mb-0.5 mx-1 inline-flex items-center gap-1 text-[10px] text-muted-foreground">
                        <span className="truncate max-w-[120px] font-medium text-foreground/80">
                          {senderName}
                        </span>
                        <span className="text-muted-foreground/70">· {identityLabel}</span>
                        <Link
                          href={`/dashboard/profile/${m.senderId}`}
                          title={`Visit ${senderName}'s profile`}
                          className="shrink-0 text-primary hover:text-primary/80 transition-colors"
                        >
                          <UserRound className="w-3 h-3" />
                          <span className="sr-only">Visit profile</span>
                        </Link>
                      </span>
                    )}
                    <div
                      className={`px-3 py-1.5 rounded-2xl text-xs leading-relaxed break-words ${
                        isMe
                          ? "bg-primary text-primary-foreground rounded-br-sm"
                          : "bg-secondary text-secondary-foreground rounded-bl-sm border border-border/50"
                      }`}
                    >
                      {m.text}
                    </div>
                  </div>
                </div>
              </div>
            );
          })
        )}
      </div>

      {/* Composer */}
      {hasCommittee && (
        <div className="p-2.5 border-t border-border/40 shrink-0">
          <div className="flex items-end gap-1.5 bg-secondary border border-border/50 rounded-xl p-1.5 focus-within:border-primary/50 transition-colors">
            <Input
              placeholder="Message committee…"
              value={input}
              onChange={(e) => setInput(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === "Enter" && !e.shiftKey) {
                  e.preventDefault();
                  handleSend();
                }
              }}
              className="border-0 bg-transparent focus-visible:ring-0 focus-visible:ring-offset-0 px-2 h-7 text-xs shadow-none"
            />
            <Button
              size="icon"
              className="shrink-0 h-7 w-7 rounded-lg"
              onClick={handleSend}
              disabled={!input.trim() || sending}
            >
              {sending ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <Send className="w-3.5 h-3.5" />}
            </Button>
          </div>
        </div>
      )}
    </div>
  );
}
