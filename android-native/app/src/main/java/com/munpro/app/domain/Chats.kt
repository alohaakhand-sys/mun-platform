package com.munpro.app.domain

// Direct messages and group chats (board A4; web lib/services/messageService.ts). A conversation
// is conversations/{id}: a direct chat's id is the two uids sorted and joined with "_", a group's
// is an auto id. The committee chat is a group with eventId + committeeId, made when a delegate
// is approved (applicationService.handlePostApprovalTasks, migrationServer).

import com.munpro.app.data.LenientMillis
import kotlinx.serialization.Serializable

@Serializable
data class Conversation(
    val id: String = "",
    val participants: List<String> = emptyList(),
    val participantNames: Map<String, String> = emptyMap(),
    val participantPhotos: Map<String, String> = emptyMap(),
    /** "direct" | "group". */
    val type: String = "direct",
    val groupName: String? = null,
    val groupPhotoUrl: String? = null,
    val createdBy: String? = null,
    @Serializable(with = LenientMillis::class) val createdAt: Long? = null,
    val admins: List<String> = emptyList(),
    val eventId: String? = null,
    val committeeId: String? = null,
    val autoGenerated: Boolean = false,
    val lastMessage: String = "",
    val lastMessageSenderId: String = "",
    @Serializable(with = LenientMillis::class) val updatedAt: Long? = null,
    val unreadCount: Map<String, Int> = emptyMap(),
    val blockedBy: List<String> = emptyList(),
) {
    val isGroup: Boolean get() = type == "group"
    /** The committee chat made on approval: the organizer's, not its members', to manage. */
    val isCommittee: Boolean get() = isGroup && autoGenerated && !eventId.isNullOrEmpty()

    fun other(me: String): String? = if (isGroup) null else participants.firstOrNull { it != me } ?: id.split("_").firstOrNull { it != me }

    fun title(me: String): String =
        if (isGroup) (if (isCommittee) committeeId?.ifEmpty { null } else null) ?: groupName?.ifEmpty { null } ?: "Group"
        else other(me)?.let { participantNames[it] }?.ifEmpty { null } ?: "MUN Pilot member"

    fun photo(me: String): String? = if (isGroup) groupPhotoUrl else other(me)?.let { participantPhotos[it] }

    fun unread(me: String): Int = unreadCount[me] ?: 0

    fun nameOf(uid: String): String = participantNames[uid]?.ifEmpty { null } ?: "Member"

    /** The list's preview line: "You: …" for my own, "Name: …" in a group, the text otherwise. */
    fun preview(me: String): String {
        val text = lastMessage.ifEmpty { return "No messages yet" }
        return when {
            lastMessageSenderId == me -> "You: $text"
            isGroup && lastMessageSenderId.isNotEmpty() && lastMessageSenderId != "system" -> "${nameOf(lastMessageSenderId).substringBefore(' ')}: $text"
            else -> text
        }
    }
}

/** conversations/{id}/messages/{id}. [pending] is a write the server hasn't confirmed yet. */
data class DirectMessage(
    val id: String,
    val senderId: String,
    val senderName: String,
    val text: String,
    val at: Long?,
    val readBy: List<String>,
    val system: Boolean,
    val pending: Boolean,
)

fun directConversationId(a: String, b: String): String = listOf(a, b).sorted().joinToString("_")

/** sending → sent → read, as the web's ticks: read once anyone but the sender has read it. */
enum class Delivery { Sending, Sent, Read }

fun DirectMessage.delivery(me: String): Delivery = when {
    pending -> Delivery.Sending
    readBy.any { it != me } -> Delivery.Read
    else -> Delivery.Sent
}
